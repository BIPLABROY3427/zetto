import axios from 'axios';
import crypto from 'crypto';

const API_BASE = process.env.AEROPAY_API_BASE;
const API_KEY = process.env.AEROPAY_API_KEY;
const MERCH_NO = process.env.AEROPAY_MERCH_NO;
const OUR_WEBHOOK_URL_PAYIN = process.env.AEROPAY_WEBHOOK_PAYIN;
const OUR_WEBHOOK_URL_PAYOUT = process.env.AEROPAY_WEBHOOK_PAYOUT;

/**
 * Generates MD5 signature for AeroPay API
 */
export const generateSign = (payload, key = API_KEY) => {
    const str = Object.keys(payload)
        .filter((k) => payload[k] !== undefined && payload[k] !== null && payload[k] !== '' && k !== 'sign')
        .sort()
        .map((k) => `${k}=${payload[k]}`)
        .join("&");
    return crypto.createHash("md5").update(str + key).digest("hex");
};

/**
 * Verify incoming webhook signature
 */
export const verifySignature = (payload, incomingSign) => {
    const generatedSign = generateSign(payload, API_KEY);
    return generatedSign.toLowerCase() === incomingSign.toLowerCase();
};

/**
 * Initiates a Pay-In (Recharge/Payment) request to AeroPay
 * @param {string} orderNo - Unique Order ID generated by our system
 * @param {number} amount - Amount in INR
 */
export const initiatePayIn = async (orderNo, amount) => {
    const payload = {
        merchNo: MERCH_NO,
        orderNo,
        amount: String(amount),
        currency: "INR",
        notifyUrl: OUR_WEBHOOK_URL_PAYIN,
    };

    payload.sign = generateSign(payload);

    try {
        const response = await axios.post(`${API_BASE}/payIn`, payload);
        return response.data;
    } catch (error) {
        console.error("AeroPay PayIn Error:", error.response?.data || error.message);
        throw new Error("Gateway failed to initiate payment");
    }
};

/**
 * Initiates a Pay-Out (Withdrawal) request to AeroPay
 */
export const initiatePayOut = async (orderNo, amount, bankDetails) => {
    const payload = {
        merchNo: MERCH_NO,
        orderNo,
        amount: String(amount),
        currency: "INR",
        acctNo: bankDetails.accountNumber,
        acctName: bankDetails.accountName,
        acctCode: bankDetails.ifscCode,
        mobile: bankDetails.mobile || '9999999999',
        notifyUrl: OUR_WEBHOOK_URL_PAYOUT,
    };

    payload.sign = generateSign(payload);

    try {
        const response = await axios.post(`${API_BASE}/payOut`, payload);
        return response.data;
    } catch (error) {
        console.error("AeroPay PayOut Error:", error.response?.data || error.message);
        if (error.response && error.response.data) {
            return error.response.data;
        }
        return { isNetworkError: true, message: error.message };
    }
};

