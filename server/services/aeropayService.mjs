/**
 * Check Upstream Gateway Balance
 */
export const upstreamBalance = async () => {
    const payload = {
        merchNo: MERCH_NO,
        timestamp: String(Date.now()), // milliseconds
        currency: "INR"
    };
    payload.sign = generateSign(payload);

    try {
        const response = await axios.post(`${API_BASE}/balance`, payload, {
            headers: {
                'Content-Type': 'application/json'
            }
        });
        return response.data;
    } catch (error) {
        if (error.response && error.response.data) {
            console.error("upstreamBalance error response:", error.response.data);
            throw new Error(`Aeropay Error: ${error.response.data.msg || 'Unknown Provider Error'}`);
        } else {
            console.error("upstreamBalance error:", error.message);
            throw new Error("Failed to query upstream balance");
        }
    }
};

